// each catalog entry's default tint list (the ext's `legacy`): [0] is a fresh pick, and a saved
// retired `variant: n` reads through the list
use super::fx::{Backdrop, Weather};

pub fn backdrop(b: Backdrop) -> [u32; 3] {
  use Backdrop::*;
  match b {
    Dawn => [0xff8700, 0xff5f87, 0xffd700],
    Graveyard => [0x808080, 0xd70000, 0x5f87ff],
    Abyss => [0x00d7ff, 0x00ffd7, 0x875fff],
    Nightfall => [0x00ff87, 0xff40af, 0x87d7ff],
    Terminal => [0x00ff5f, 0xffb000, 0xc0c0c0],
    Furnace => [0xff3700, 0x00afff, 0xaf5fff],
    Ocean => [0xff8700, 0x5f87ff, 0x00d7ff],
    Skyline => [0xff40af, 0xff8700, 0xff87af],
    Orbit => [0xff5f00, 0xaf5fff, 0x00d7ff],
    Synth => [0xff40af, 0x00e5ff, 0xffd700],
    Glacier => [0x5f87af, 0xaf5f87, 0x00afd7],
    Sakura => [0xffafd7, 0xff87af, 0xaf5fff],
    Volcano => [0xff5f00, 0xffd700, 0xaf5fff],
    Alpine => [0xffaf5f, 0x87d7ff, 0xff5f87],
    Swamp => [0x87ff5f, 0x5fd7ff, 0xffff5f],
    Castle => [0x5f87ff, 0xd70000, 0xffaf87],
    Moon => [0x5fafff, 0x87d7ff, 0xffd7af],
    Circuit => [0x00ff5f, 0x00afff, 0xffb000],
    Eclipse => [0xffd7af, 0xff5f5f, 0xaf87ff],
    Arcade => [0xff40af, 0x00e5ff, 0xffd700],
    Bamboo => [0x5faf5f, 0x5f87af, 0xd7af87],
    Giza => [0xff8700, 0x5f87ff, 0xd7af5f],
  }
}

pub fn weather(w: Weather) -> [u32; 3] {
  use Weather::*;
  match w {
    Rain | Storm => [0x9db4c9, 0xd70000, 0x87ff00],
    Snow => [0xffffff, 0x9e9e9e, 0xffd75f],
    Fog => [0xffaf87, 0xc0c8d0, 0x87ff5f],
    Embers => [0xff8700, 0x00d7ff, 0xff40af],
    Glyphs => [0x00ff87, 0xffb000, 0x00e5ff],
    Petals => [0xffafd7, 0xffffff, 0xffd75f],
    Bubbles => [0xffffff, 0x87ffd7, 0xd7afff],
    Fireflies => [0xd7ff5f, 0xffd75f, 0x87ffff],
    Leaves => [0xff8700, 0xd70000, 0x87ff5f],
    Sparks => [0xffffff, 0xffd75f, 0x87d7ff],
    Dust => [0xd7af87, 0x9e9e9e, 0xffd75f],
    Confetti => [0xff5f87, 0xffffff, 0xff8700],
    Meteors => [0xffffff, 0xffd75f, 0x87ffff],
    Hearts => [0xff5fd7, 0xff0000, 0xffffff],
  }
}
